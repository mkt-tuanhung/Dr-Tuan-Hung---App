import { launch, close, openAs, shot, check, sql, U } from './lib.mjs';
await launch();
const t = sql("select id from mw_tasks where title = 'Video hỏi đáp gọt hàm V-line' order by created_at desc limit 1");
const { page } = await openAs(U.lead, { tab: `mkt_workspace#task:${t}` });
const d = page.getByRole('dialog');
await d.getByRole('tab', { name: 'Source & kịch bản' }).click();
await d.getByRole('button', { name: 'Gắn source' }).first().click();
const dlg = page.getByRole('dialog', { name: 'Gắn source từ Kho Media' });
const box = dlg.getByPlaceholder(/Tìm mã source/);
await box.waitFor();
const y0 = (await box.boundingBox()).y, yS = (await dlg.getByText('Gợi ý cho thẻ này').boundingBox())?.y;
check(yS && y0 < yS, 'Ô tìm kiếm nằm trên cùng, trước phần gợi ý');
await box.fill('nga10');
await page.waitForTimeout(800);
check(await dlg.getByText('Nga10092026_01').count() === 1 && await dlg.getByText('Gợi ý cho thẻ này').count() === 0, 'Tìm theo mã (không dấu, không phân biệt hoa thường) + ẩn gợi ý khi đang tìm');
await box.fill('Nguyễn Thị');
await page.waitForTimeout(1200);
check(await dlg.getByText('Lan01092026_01').count() === 1 && await dlg.getByText('Hoa27102026_01').count() === 1 && await dlg.getByText('Mai15102026_01').count() === 0, 'Tìm theo tên khách (lọc ở server, không hiện tên)');
check(await dlg.getByText('Nguyễn Thị Lan').count() === 0, 'Không lộ tên khách trong danh sách');
await shot(page, 'kho_search_name');
await box.fill('15/10');
await page.waitForTimeout(800);
check(await dlg.getByText('Mai15102026_01').count() === 1, 'Tìm theo ngày quay 15/10');
await box.fill('zzzz');
await page.waitForTimeout(800);
check(await dlg.getByText(/Không thấy source nào/).count() === 1, 'Không có kết quả -> báo rõ');
await box.fill('');
await page.waitForTimeout(500);
check(await dlg.getByText('Gợi ý cho thẻ này').count() === 1, 'Xoá tìm -> gợi ý hiện lại');
await close();
